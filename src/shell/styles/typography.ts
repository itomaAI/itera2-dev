/**
 * src/shell/styles/typography.ts
 * Itera OS v2: 文字の役割語彙（Typography Roles）
 *
 * ─────────────────────────────────────────────────────────────
 * なぜこのファイルがあるか
 * ─────────────────────────────────────────────────────────────
 * 2026-08-17 の調査で、ホストシェル内に「小さい大文字ラベル」の書式が
 * 18種類存在していた。原因は見た目の趣味の相違ではなく、
 * **役割に名前が無かったこと**である。名前が無いと次に書く人は既存を探せず、
 * 19個目の綴りを発明する。だから見た目を揃える前に語彙を揃える。
 *
 * ─────────────────────────────────────────────────────────────
 * 設計原理: 反復回数が増えるほど、装飾は減らす
 * ─────────────────────────────────────────────────────────────
 * tracking-widest の等幅大文字は「1画面に1回しか出ない」から成立する装飾で、
 * 同じものを50回スクロールさせるとノイズになる。
 * したがって装飾の量は「その札が何回出るか」で決める。
 *
 *   LABEL_KICKER  … 1面に1回      → 装飾してよい（mono + tracking-widest）
 *   LABEL_SECTION … 1面に数回      → 中間（sans bold + tracking-wider）
 *   LABEL_STREAM  … N回・スクロール → 素にする（字間指定なし）
 *
 * チャットパネルのターン見出し（USER / MODEL / SYSTEM / ITERA: REPORT）が
 * 読みやすいのは、この原理に従って地味だからである。ここを他所に合わせて
 * 飾ってはならない。
 *
 * ─────────────────────────────────────────────────────────────
 * 使い方
 * ─────────────────────────────────────────────────────────────
 * 色と余白は含めない。同じ役割でも場所によって
 * text-text-muted / opacity-50 と落とし方が変わるため、呼び出し側で足す。
 *
 *   header.className = `mb-1 opacity-50 ${LABEL_STREAM}`;
 *   `<div class="${LABEL_KICKER} text-text-muted mt-0.5">Properties</div>`
 */

/** モーダル等の見出し。文章として読ませるので大文字化も字間調整もしない。 */
export const LABEL_TITLE = 'font-bold text-base leading-tight';

/**
 * 見出しに添える小さな飾り札（kicker）。1つの面に1回だけ出ることが条件。
 * 例: "Properties" / "Sync Providers" / "Real-time Process List"
 */
export const LABEL_KICKER = 'font-mono text-[0.625rem] uppercase tracking-widest';

/**
 * 領域や入力欄に付ける見出し。静止していて、1面に数回まで。
 * 例: "Storage" / "Itera Agent" / API キーの各ラベル
 */
export const LABEL_SECTION = 'font-bold text-[0.625rem] uppercase tracking-wider';

/**
 * 流れの中で反復し、スクロールする単位に付ける札。
 * 例: チャットの各ターン見出し。
 * 字間を空けないのは意図的。反復するものを飾ると本文が負ける。
 */
export const LABEL_STREAM = 'font-bold text-[0.625rem] uppercase';

/**
 * ─────────────────────────────────────────────────────────────
 * 既知の逸脱（2026-08-17 時点・未是正）
 * ─────────────────────────────────────────────────────────────
 * 下記は役割としては LABEL_SECTION だが、寸法が 12px / 14px で書かれている。
 * 揃えると見た目が変わるため、今回は意図的に触っていない。
 *
 *   - index.html の一部（12px の sans bold 大文字・字間 wider）
 *   - SyncModal.ts / DialogService.ts（同上、および 14px 版）
 *
 * px 固定のサイズ指定は 2026-08-17 にホストシェルから一掃した（44件 → 0件）。
 * 新しく px 固定を持ち込まないこと。外観設定のフォントサイズが効かなくなる。
 *
 * ─────────────────────────────────────────────────────────────
 * 単位の使い分け（2026-08-17）
 * ─────────────────────────────────────────────────────────────
 * **チャットの枠の中は em、枠の外は rem。**
 *
 * 会話本文の寸法（.chat-body）と機構レイヤの寸法（.chat-system-message）は
 * 利用者が外観設定で変えられる。したがって枠の中身を rem で書くと、
 * 本文だけが伸縮して見出しやコードとの上下関係が壊れる。
 * 実際、本文を 16px にすると rem 基準の h3（14px）は本文より小さくなる。
 *
 *   枠の中（markdownLite の見出し・コード、LpmlRenderer のタグボックス）
 *     → em。本文に対する比で書く。
 *   枠の外（このファイルのラベル、エクスプローラ、モーダル、ステータスバー）
 *     → rem。全体スケール（root font-size）に追従させる。
 *
 * 例外として、枠の中にあっても「Loading image...」「(File not found)」のような
 * システムの注記は rem のままでよい。あれは利用者やIteraの言葉ではなく、
 * 機構側の語彙が会話の中に差し込まれているものだからである。
 *
 * 【注意】この注記に Tailwind のクラス名をそのまま書かないこと。
 * content 走査の対象になり未使用の CSS が生成されるうえ、
 * 使用箇所を数える調査で偽陽性になる（実際に1件混入させた）。
 */
