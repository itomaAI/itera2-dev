  const FALLBACK = 'en-US';
  let LOCALE = FALLBACK;

  /** 鍵の文を、いまの言語で返す。{name} は vars の値に置き換える。表に無い鍵は鍵そのものを返す */
  function t(key, vars) {
    let s = T[LOCALE][key];
    if (s === undefined) s = T[FALLBACK][key];
    if (s === undefined) return key;
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m));
  }
  const has = (key) => T[FALLBACK][key] !== undefined;

  /** OS の appearance.locale（'ja'・'en'・'ja-JP' など）から言語を決める。変わったら true */
  function setLocale(locale) {
    const next = /^ja(-|$)/i.test(String(locale || '')) ? 'ja-JP' : FALLBACK;
    const changed = next !== LOCALE;
    LOCALE = next;
    return changed;
  }

  /** HTML に置いてある文字を差し替える（data-i18n は中の文字、data-i18n-title は title） */
  function applyStatic(root) {
    const doc = root || document;
    doc.documentElement.lang = LOCALE === 'ja-JP' ? 'ja' : 'en';
    doc.title = t('app.title');
    doc.querySelectorAll('[data-i18n]').forEach((e) => (e.textContent = t(e.dataset.i18n)));
    doc.querySelectorAll('[data-i18n-title]').forEach((e) => (e.title = t(e.dataset.i18nTitle)));
  }

  global.DesignI18n = {
    T,
    t,
    has,
    setLocale,
    applyStatic,
    get locale() {
      return LOCALE;
    },
  };
